    private void changeCount(SlotDef slot, SimState.PartSel sel, int direction) {
        List<Integer> counts = slot.allowedCounts();
        int idx = counts.indexOf(sel.count());
        if (idx < 0) idx = 0;
        idx = Mth.clamp(idx + direction, 0, counts.size() - 1);
        sel.resize(counts.get(idx));
        markDirty();
    }

    private void openGearPopup() {
        List<ListPopup.Row<ResourceLocation>> rows = new ArrayList<>();
        for (Item item : catalog.gearItems()) {
            ResourceLocation id = BuiltInRegistries.ITEM.getKey(item);
            rows.add(ListPopup.Row.of(id, gearIcon(item), GearCatalog.itemName(item), id.toString(), null, 0));
        }
        closePopup();
        popupSlot = null;
        popup = new ListPopup<>(font, rows, List.of(), STATE.gearItem, null, false,
                leftX, PAD + 24, Math.max(160, leftW), width, height, Component.translatable("sgsim.search"));
        addWidget(popup.search);
        setFocused(popup.search);
    }

    private void applyGearItem(@Nullable ResourceLocation id) {
        if (id == null) return;
        STATE.gearItem = id;
        partsScroll = 0;
        tooltipScroll = 0;
        ensureState();
        markDirty();
    }

    private void openMaterialPopup(SlotDef slot, int unit, int anchorX, int anchorY) {
        GearItem gearItem = GearCatalog.gearItem(STATE.gearItem);
        GearType gearType = gearItem != null ? gearItem.getGearType() : slot.item().getGearType();
        SimState.PartSel sel = STATE.parts.get(slot.typeId());
        MaterialGrade grade = sel != null && unit < sel.count() ? sel.grades.get(unit) : MaterialGrade.NONE;
        ResourceLocation current = sel != null && unit < sel.count() ? sel.materials.get(unit) : null;

        List<ListPopup.Row<ResourceLocation>> rows = new ArrayList<>();
        rows.add(ListPopup.Row.of(null, ItemStack.EMPTY, Component.translatable("sgsim.none"), "", null, 0));
        Map<ResourceLocation, MaterialInstance> previews = new HashMap<>();
        for (ResourceLocation id : catalog.materialsFor(slot)) {
            MaterialInstance preview = previewMaterial(slot, id, grade);
            if (preview != null) previews.put(id, preview);
            // Search matches name, id and the traits this material gives in this part
            String extra = id + (preview != null ? StatValues.traitText(preview, slot.type(), gearType) : "");
            PartSource source = catalog.source(slot, id);
            String tag = source == null || source == PartSource.CRAFTING ? null
                    : Component.translatable("sgsim.popup." + source.name().toLowerCase(Locale.ROOT)).getString();
            int tagColor = source == PartSource.OTHER ? 0xFFAA00 : 0x55FFFF;
            rows.add(ListPopup.Row.of(id, catalog.icon(slot, id), GearCatalog.materialName(id, slot.type()), extra, tag, tagColor));
        }

        // Sort options: every number stat at least one of these materials affects in this part
        List<ListPopup.Sort<ResourceLocation>> sorts = new ArrayList<>();
        for (NumberProperty property : StatValues.numberProperties()) {
            boolean relevant = false;
            for (MaterialInstance m : previews.values()) {
                if (!Double.isNaN(StatValues.value(m, slot.type(), gearType, property))) {
                    relevant = true;
                    break;
                }
            }
            if (!relevant) continue;
            sorts.add(new ListPopup.Sort<>(StatValues.key(property), property.getDisplayName(), id -> {
                MaterialInstance m = previews.get(id);
                return m != null ? StatValues.value(m, slot.type(), gearType, property) : Double.NaN;
            }));
        }
        sorts.sort(Comparator.comparing(srt -> srt.name().getString()));

        closePopup();
        popupSlot = slot;
        popupUnit = unit;
        popup = new ListPopup<>(font, rows, sorts, current, sortKey, sortDescending,
                anchorX, anchorY, 210, width, height, Component.translatable("sgsim.search.materials"));
        addWidget(popup.search);
        setFocused(popup.search);
    }

    private void closePopup() {
        if (popup != null) {
            if (popupSlot != null) {
                sortKey = popup.sortKey();
                sortDescending = popup.descending();
            }
            removeWidget(popup.search);
            popup = null;
            setFocused(null);
        }
    }

    private void pickFromPopup(@Nullable ResourceLocation value) {
        SlotDef slot = popupSlot;
        int unit = popupUnit;
        closePopup();
        if (slot == null) applyGearItem(value);
        else applyMaterial(slot, unit, value);
    }

    private void applyMaterial(SlotDef slot, int unit, @Nullable ResourceLocation id) {
        if (id == null) {
            STATE.parts.remove(slot.typeId());
        } else {
            SimState.PartSel sel = STATE.parts.computeIfAbsent(slot.typeId(),
                    k -> new SimState.PartSel(slot.defaultCount(), null));
            PartSource source = catalog.source(slot, id);
            if (source != null && source.gradeLocked) {
                // Ready-made parts: copy the route's unit count, grades are not selectable
                sel.resize(source == PartSource.FIXED_RECIPE ? slot.fixedFor(id).getFirst().materials().size() : 1);
                sel.setAllMaterials(id);
                sel.setAllGrades(MaterialGrade.NONE);
            } else if (STATE.mixedMaterials && unit < sel.count()) {
                sel.materials.set(unit, id);
            } else {
                sel.setAllMaterials(id);
            }
        }
        markDirty();
    }

    /** A representative icon for a gear item: the item as it would come out with its default parts. */
    private ItemStack gearIcon(Item item) {
        return gearIcons.computeIfAbsent(item, i -> {
            SimState temp = new SimState();
            temp.gearItem = BuiltInRegistries.ITEM.getKey(i);
            if (i instanceof GearItem gi) {
                for (SlotDef slot : catalog.slotsFor(gi)) {
                    if (!slot.required()) continue;
                    ResourceLocation m = defaultMaterial(slot);
                    if (m != null) temp.parts.put(slot.typeId(), new SimState.PartSel(slot.defaultCount(), m));
                }
            }
            ItemStack built = GearSimulator.build(catalog, temp).stack();
            return built.isEmpty() ? new ItemStack(i) : built;
        });
    }

    private void giveCreative() {
        var player = minecraft.player;
        var gameMode = minecraft.gameMode;
        if (player == null || gameMode == null || !player.isCreative() || result.stack().isEmpty()) return;
        int free = player.getInventory().getFreeSlot();
        if (free < 0) {
            player.displayClientMessage(Component.translatable("sgsim.give.full").withStyle(ChatFormatting.RED), true);
            return;
        }
        ItemStack copy = result.stack().copy();
        player.getInventory().setItem(free, copy);
        // Inventory menu slot ids: hotbar 0-8 -> 36-44, main inventory 9-35 -> 9-35
        int menuSlot = free < 9 ? free + 36 : free;
        gameMode.handleCreativeModeItemAdd(copy, menuSlot);
        player.displayClientMessage(Component.translatable("sgsim.give.done", copy.getHoverName()), true);
    }

