    @Override
    public boolean mouseClicked(double mouseX, double mouseY, int button) {
        if (popup != null) {
            ListPopup.Click click = popup.click(mouseX, mouseY, button);
            if (click == ListPopup.Click.OUTSIDE) {
                closePopup(); // click outside closes it
            } else if (click == ListPopup.Click.PICKED && button == GLFW.GLFW_MOUSE_BUTTON_LEFT && popup.picked() != null) {
                pickFromPopup(popup.picked().value());
            } else {
                setFocused(popup.search);
            }
            return true;
        }
        if (super.mouseClicked(mouseX, mouseY, button)) return true;
        for (Hit hit : List.copyOf(hits)) {
            if (hit.click() != null && hit.contains(mouseX, mouseY)) {
                hit.click().click(button);
                return true;
            }
        }
        return false;
    }

    @Override
    public boolean mouseScrolled(double mouseX, double mouseY, double scrollX, double scrollY) {
        int dir = (int) Math.signum(scrollY);
        if (dir == 0) return false;
        if (popup != null) {
            if (popup.contains(mouseX, mouseY)) popup.scroll(dir);
            return true;
        }
        for (Hit hit : hits) {
            if (hit.scroll() != null && hit.contains(mouseX, mouseY)) {
                hit.scroll().scroll(dir);
                return true;
            }
        }
        if (mouseX >= leftX && mouseX < leftX + leftW && mouseY >= partsTop && mouseY < partsBottom) {
            partsScroll = Mth.clamp(partsScroll - dir * 12, 0, Math.max(0, partsContentH - (partsBottom - partsTop)));
            return true;
        }
        if (mouseX >= rightX && mouseY >= tooltipTop && mouseY < tooltipBottom) {
            tooltipScroll = Mth.clamp(tooltipScroll - dir * LINE_H * 2, 0,
                    Math.max(0, tooltipContentH - (tooltipBottom - tooltipTop)));
            return true;
        }
        return super.mouseScrolled(mouseX, mouseY, scrollX, scrollY);
    }

    @Override
    public boolean keyPressed(int keyCode, int scanCode, int modifiers) {
        // Flip the Silent Gear stat page of the material tooltip under the mouse
        if (!pageKey.isEmpty()) {
            boolean typing = popup != null; // letters go to the search box while the popup is open
            if (keyCode == GLFW.GLFW_KEY_RIGHT || (!typing && KeyTracker.CYCLE_NEXT.matches(keyCode, scanCode))) {
                pageOffset++;
                return true;
            }
            if (keyCode == GLFW.GLFW_KEY_LEFT || (!typing && KeyTracker.CYCLE_BACK.matches(keyCode, scanCode))) {
                pageOffset--;
                return true;
            }
        }
        if (popup != null) {
            if (keyCode == GLFW.GLFW_KEY_ESCAPE) {
                closePopup();
                return true;
            }
            if (keyCode == GLFW.GLFW_KEY_ENTER || keyCode == GLFW.GLFW_KEY_KP_ENTER) {
                ListPopup.Row<ResourceLocation> first = popup.firstMatch();
                if (first != null) pickFromPopup(first.value());
                else closePopup();
                return true;
            }
            super.keyPressed(keyCode, scanCode, modifiers); // to the search box
            return true;
        }
        // Let the open key close the screen too
        if (dev.sgsim.SgSimMod.OPEN_KEY.matches(keyCode, scanCode)) {
            onClose();
            return true;
        }
        return super.keyPressed(keyCode, scanCode, modifiers);
    }

