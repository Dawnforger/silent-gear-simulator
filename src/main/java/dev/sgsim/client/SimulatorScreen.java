    private static int gradeColor(MaterialGrade grade) {
        return switch (grade) {
            case NONE -> 0xAAAAAA;
            case E, D -> 0xFFFFFF;
            case C, B -> 0x55FF55;
            case A -> 0x55FFFF;
            case S, SS -> 0xFFAA00;
            case SSS -> 0xFF55FF;
            case MAX -> 0xFF5555;
        };
    }

